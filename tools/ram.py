def que_es(a):
    """(nombre, explicacion) de la direccion a, o None."""
    if a in VARS:
        return VARS[a]
    for d, h, n, q in ZONAS:
        if d <= a < h:
            if n == "objetos":
                k, i = divmod(a - 0xC850, 4)
                return ("objeto_%d" % (k + 1), "el OBJETO %d (byte %d de 4; p06:BAC2)" % (k + 1, i))
            if n == "bichos":
                k, i = divmod(a - 0xD000, 0x80)
                return ("bicho_%d" % k, "la ficha del bicho %d, byte 0x%02X (p01:74B7)" % (k, i))
            return (n, q)
    return None

